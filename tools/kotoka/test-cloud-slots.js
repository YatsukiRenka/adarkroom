import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context = { module: { exports: {} } };
vm.runInNewContext(fs.readFileSync(new URL('../../script/kotoka/cloud-slots.js', import.meta.url), 'utf8'), context);
const slots = context.module.exports;
[1, 20].forEach(n => assert(slots.validSlot(n)));
[0, 21, -1, 1.5, '1', NaN].forEach(n => assert(!slots.validSlot(n)));
assert.strictEqual(slots.formatDate('bad'), null);
assert.strictEqual(slots.formatDate(null), null);
const date = new Date(2026, 0, 2, 3, 4);
assert.strictEqual(slots.formatDate(date.toISOString()), '2026-01-02 03:04');
const rows = slots.rows({ slots: [{ slot: 20, updatedAt: date.toISOString(), summary: { wood: 0 } }, { slot: 21 }] });
assert.strictEqual(rows.length, 20);
assert.deepStrictEqual(Array.from(rows, r => r.slot), Array.from({length: 20}, (_, i) => i + 1));
assert.strictEqual(rows[0].occupied, false);
assert.strictEqual(rows[19].occupied, true);
assert.strictEqual(rows[19].summary.wood, 0);
assert.strictEqual(rows[19].date, '2026-01-02 03:04');
assert.strictEqual(slots.rows({slots: []}).filter(r => r.occupied).length, 0);
console.log('cloud-slots tests passed');

const calls = [];
const storage = { 'kotoka.cloud': 'baseline' };
const saveContext = { module: { exports: {} }, localStorage: { setItem(k, v) { storage[k] = v; calls.push('write'); } }, Engine: { saveGame() { calls.push('old save'); } }, location: { reload() { calls.push('reload'); saveContext.Engine.saveGame(); } } };
vm.runInNewContext(fs.readFileSync(new URL('../../script/kotoka/cloud-save.js', import.meta.url), 'utf8'), saveContext);
saveContext.module.exports.replaceLocalSave('slot state');
assert.deepEqual(calls, ['write', 'reload']);
assert.equal(storage.gameState, 'slot state');
assert.equal(storage['kotoka.cloud'], 'baseline');
