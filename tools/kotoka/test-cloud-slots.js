import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context = { module: { exports: {} } };
vm.runInNewContext(fs.readFileSync(new URL('../../script/kotoka/cloud-slots.js', import.meta.url), 'utf8'), context);
const slots = context.module.exports;
[1, 19].forEach(n => assert(slots.validSlot(n)));
[0, 20, -1, 1.5, '1', NaN].forEach(n => assert(!slots.validSlot(n)));
assert.equal(slots.formatDate('bad'), null);
assert.equal(slots.formatDate(new Date(2026, 0, 2, 3, 4)), '2026-01-02 03:04');
assert.equal(slots.validateName('  hello  '), 'hello');
['', ' ', 'x'.repeat(41), 'a\u0000b', 'a\u0085b'].forEach(n => assert.equal(slots.validateName(n), null));
assert.equal(slots.validateName('😀'.repeat(40)), '😀'.repeat(40));
assert.equal(slots.freeSlot([]), 1);
assert.equal(slots.freeSlot([{slot: 1}, {slot: 3}]), 2);
const all = Array.from({length: 19}, (_, i) => ({slot: i + 1, updatedAt: new Date(2026, 0, i + 1).toISOString()}));
assert.equal(slots.freeSlot(all), null);
const first = slots.pageModel(all, null, 1);
assert.equal(first.rows[0].auto, true);
assert.equal(first.rows[1].slot, 19);
assert.equal(first.rows.length, 5);
assert.equal(first.total, 4);
assert.equal(slots.pageModel(all, null, 99).page, 4);
assert.equal(slots.pageModel([], null, 4).page, 1);
assert.equal(slots.pageModel([], null, 1).total, 1);
console.log('cloud-slots tests passed');

const calls = [];
const storage = { 'kotoka.cloud': 'baseline' };
const saveContext = { module: { exports: {} }, localStorage: { setItem(k, v) { storage[k] = v; calls.push('write'); } }, Engine: { saveGame() { calls.push('old save'); } }, location: { reload() { calls.push('reload'); saveContext.Engine.saveGame(); } } };
vm.runInNewContext(fs.readFileSync(new URL('../../script/kotoka/cloud-save.js', import.meta.url), 'utf8'), saveContext);
saveContext.module.exports.replaceLocalSave('slot state');
assert.deepEqual(calls, ['write', 'reload']);
assert.equal(storage.gameState, 'slot state');
assert.equal(storage['kotoka.cloud'], 'baseline');
