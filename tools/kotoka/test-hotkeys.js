import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { runInThisContext } from 'node:vm';
const source = readFileSync(new URL('../../script/kotoka/hotkeys.js', import.meta.url), 'utf8');
const exported = { exports: {} };
runInThisContext('(function(module) {\n' + source + '\n})')(exported);
const logic = exported.exports;
const defaults = logic.load(null);
assert.equal(defaults.attack1, 'Digit1');
assert.equal(defaults.leave, 'Enter');
for(const raw of ['oops', '[]', 'null', '{"eat":42}', '{"eat":""}']) assert.deepEqual(logic.load(raw), defaults);
assert.deepEqual(logic.load(JSON.stringify(defaults)), defaults);
const merged = logic.load('{"eat":"Digit1","meds":null}');
assert.equal(merged.eat, 'Digit1');
assert.equal(merged.attack1, null);
assert.equal(merged.meds, null);
assert.equal(merged.shield, 'KeyG');
const rebound = logic.rebind(defaults, 'eat', 'KeyR');
assert.equal(rebound.meds, null);
assert.equal(rebound.eat, 'KeyR');
assert.equal(defaults.meds, 'KeyR');
assert.equal(logic.rebind(rebound, 'eat', null).eat, null);
assert.equal(new Set(Object.values(merged).filter(Boolean)).size, Object.values(merged).filter(Boolean).length);
for(const [code, name] of [['Digit1', '1'], ['KeyE', 'E'], ['Numpad1', 'Num1'], ['Space', 'Space'], ['Enter', 'Enter'], ['ArrowUp', '↑'], ['ArrowDown', '↓'], ['ArrowLeft', '←'], ['ArrowRight', '→'], ['F12', 'F12'], [null, '']]) assert.equal(logic.display(code), name);
console.log('hotkeys logic tests passed');
